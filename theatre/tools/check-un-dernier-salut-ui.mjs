// Real desktop and phone interaction for Show XII.
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import { resolve, join } from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
const ROOT=resolve(import.meta.dirname,'..');
const OUT=resolve(ROOT,'../productions/un-dernier-salut/render/qa');
mkdirSync(OUT,{recursive:true});
const server=await createServer({root:ROOT,configFile:join(ROOT,'vite.config.ts'),server:{port:0,hmr:false,watch:null},logLevel:'error'});
await server.listen();
const origin=`http://localhost:${server.httpServer.address().port}`;
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required','--use-angle=d3d11']});
const errors=[]; const report={};
const desktop=await browser.newPage({viewport:{width:1440,height:1000}});
desktop.on('pageerror',e=>errors.push(e.message));
await desktop.addInitScript(()=>{const Native=window.Audio; window.Audio=function(...args){const a=new Native(...args);window.qaAudio=a;return a;};});
await desktop.goto(`${origin}/?p=un-dernier-salut`);
await desktop.locator('#enter:not([disabled])').waitFor({timeout:120000});
await desktop.locator('#enter').click();
await desktop.locator('#lobby:not(.away)').waitFor({timeout:30000});
await desktop.waitForFunction(()=>getComputedStyle(document.getElementById('lobby')).opacity==='1');
report.title=await desktop.locator('#bill-en').textContent();
report.about=await desktop.locator('#bill-about').textContent();
report.posterCount=await desktop.locator('#wall .poster').count();
if(report.title!=='Un dernier salut'||report.posterCount!==12)throw Error('Wrong programme or show count');
await desktop.screenshot({path:join(OUT,'programme-desktop.png')});
await desktop.locator('#bill-en-toggle').click();
if(await desktop.locator('#bill-en-toggle').getAttribute('aria-pressed')!=='true')throw Error('English toggle');
await desktop.locator('#raise').click();
await desktop.waitForFunction(()=>window.qaAudio?.currentTime>0.2,{},{timeout:30000});
report.audio=await desktop.evaluate(()=>({duration:window.qaAudio.duration,src:window.qaAudio.currentSrc}));
if(Math.abs(report.audio.duration-327.92)>.1)throw Error('Wrong audio duration');
await desktop.evaluate(()=>{window.qaAudio.currentTime=79;});
await desktop.waitForFunction(()=>document.querySelector('.surtitles .main')?.textContent.includes('Un pas pour toi'),{},{timeout:10000});
report.subtitles=await desktop.locator('.surtitles').evaluate(e=>({main:e.querySelector('.main').textContent,second:e.querySelector('.second').textContent,english:e.querySelector('.en').textContent,englishOn:e.dataset.en}));
await desktop.keyboard.press('Space');
await desktop.locator('#interval.on').waitFor();
await desktop.screenshot({path:join(OUT,'play-english.png')});
await desktop.keyboard.press('Escape');
await desktop.waitForFunction(()=>document.body.classList.contains('at-wall'));
await desktop.locator('#wall .poster[data-id="un-dernier-salut"]').click();
report.resume=await desktop.locator('#raise').textContent();
if(report.resume!=='Resume the Play')throw Error('Resume seal');
await desktop.close();
const mobile=await browser.newPage({viewport:{width:390,height:844},screen:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
mobile.on('pageerror',e=>errors.push(e.message));
await mobile.goto(`${origin}/?p=un-dernier-salut`);
await mobile.locator('#enter:not([disabled])').waitFor({timeout:120000});
await mobile.locator('#enter').click();
await mobile.locator('#lobby:not(.away)').waitFor({timeout:30000});
await mobile.waitForFunction(()=>getComputedStyle(document.getElementById('lobby')).opacity==='1');
report.mobile=await mobile.locator('.billwrap').evaluate(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height,viewport:[innerWidth,innerHeight]};});
report.castOverflow=await mobile.locator('.bill .cast').evaluate(e=>e.scrollWidth>e.clientWidth+1);
if(report.castOverflow)throw Error('Phone cast row overflows');
if(report.mobile.x<0||report.mobile.y<0||report.mobile.x+report.mobile.width>391||report.mobile.y+report.mobile.height>845)throw Error('Phone programme overflows');
await mobile.screenshot({path:join(OUT,'programme-phone.png')});
await mobile.close();
report.errors=errors;
writeFileSync(join(OUT,'ui.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();await server.close();
if(errors.length)process.exitCode=1;
